#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import prettier from "prettier";

const root = process.cwd();
const FEATURE_MESSAGES = JSON.parse(
  fs.readFileSync(path.join(root, "src", "i18n", "client-feature-message-map.json"), "utf8")
);
const sourceCatalogs = Object.fromEntries(
  ["en", "zh"].map((locale) => [
    locale,
    fs.readFileSync(path.join(root, "messages", `${locale}.json`), "utf8"),
  ])
);
const messageVersion = crypto
  .createHash("sha256")
  .update(JSON.stringify(FEATURE_MESSAGES))
  .update(JSON.stringify(sourceCatalogs))
  .digest("hex")
  .slice(0, 16);
const versionFilePath = path.join(root, "src", "i18n", "feature-message-version.ts");
const versionFile = `// Generated by scripts/generate-i18n-catalogs.mjs. Do not edit manually.
export const FEATURE_MESSAGE_VERSION = "${messageVersion}";
`;
if (fs.readFileSync(versionFilePath, "utf8") !== versionFile) {
  fs.writeFileSync(versionFilePath, versionFile, "utf8");
}
for (const locale of ["en", "zh"]) {
  const catalog = JSON.parse(
    fs.readFileSync(path.join(root, "messages", `${locale}.json`), "utf8")
  );
  const directory = path.join(root, "messages", locale);
  fs.mkdirSync(directory, { recursive: true });
  for (const [feature, namespaces] of Object.entries(FEATURE_MESSAGES)) {
    const selected = Object.fromEntries(
      namespaces
        .filter((namespace) => namespace in catalog)
        .map((namespace) => [namespace, catalog[namespace]])
    );
    const outputPath = path.join(directory, `${feature}.json`);
    const formatted = await prettier.format(`${JSON.stringify(selected, null, 2)}\n`, {
      filepath: outputPath,
    });
    fs.writeFileSync(outputPath, formatted, "utf8");
  }
}
